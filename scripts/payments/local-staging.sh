#!/usr/bin/env bash
# Local Stripe payment staging for Golf Society Hub.
# Refuses production project eaenzjwecrrbhibrvgsb and live Stripe keys.
# The generated account password stays in gitignored staging.local.env.
# That name does not start with ".env". Expo's web bundle loads every
# project-root file matching /^\.\/\.env/ and fails if one of them is not a
# standard Expo env file.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

ENV_FILE="${STAGING_ENV_FILE:-$ROOT/staging.local.env}"
SEED_FILE="$ROOT/supabase/seeds/staging_m4_zgs_payments.sql"
PRODUCTION_REF="eaenzjwecrrbhibrvgsb"
VALIDATE_DB="${STAGING_VALIDATE_DB:-gsh_migration_validate}"

usage() {
  cat <<'EOF'
Usage: scripts/payments/local-staging.sh <command>

  setup                 Generate staging.local.env, apply local migrations, seed
  seed                  Seed Staging M4 / Staging ZGS on the local database
  start                 Start Expo web and the payment API with staging env
  check                 Ask the payment API whether it can query the local database
  repair-local-history  Rename old local migration versions after the timestamp fix
  validate-migrations   Apply all migrations to a fresh local database and exit

Online payments stay disabled. Do not point this at production.
setup uses Docker when the daemon is running. Otherwise, if
"supabase start --help" lists --runtime native after
SUPABASE_EXPERIMENTAL_STACK=1, it starts that native stack. A local
Postgres socket is not treated as Supabase Auth.
EOF
}

refuse_value() {
  local label="$1"
  local value="${2:-}"
  local lower
  lower="$(printf '%s' "$value" | tr '[:upper:]' '[:lower:]')"
  if [[ "$lower" == *"$PRODUCTION_REF"* || "$lower" == *sk_live_* || "$lower" == *pk_live_* ]]; then
    echo "Refusing staging: ${label} points at production or a live Stripe key." >&2
    exit 1
  fi
}

assert_local_database_url() {
  local url="$1"
  python3 - "$url" <<'PY'
import sys
from urllib.parse import urlparse
raw = sys.argv[1]
low = raw.lower()
if "eaenzjwecrrbhibrvgsb" in low or "sk_live_" in low or "pk_live_" in low:
    sys.exit(2)
host = (urlparse(raw).hostname or "").lower()
if host in ("", "127.0.0.1", "localhost", "::1"):
    print("127.0.0.1")
    sys.exit(0)
sys.exit(3)
PY
}

ensure_env_file() {
  python3 - "$ENV_FILE" <<'PY'
import pathlib, secrets, sys
path = pathlib.Path(sys.argv[1])
vals = {}
if path.exists():
    for line in path.read_text().splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        vals[key] = value
password = vals.get("STAGING_ACCOUNT_PASSWORD", "")
if len(password) < 16:
    vals["STAGING_ACCOUNT_PASSWORD"] = secrets.token_hex(24)
defaults = {
    "EXPO_PUBLIC_SUPABASE_URL": "http://127.0.0.1:54321",
    "SUPABASE_URL": "http://127.0.0.1:54321",
    "EXPO_PUBLIC_SUPABASE_ANON_KEY": "",
    "SUPABASE_SERVICE_ROLE_KEY": "",
    "STAGING_DATABASE_URL": "postgresql://ubuntu@localhost/gsh_payment_staging?host=/var/run/postgresql",
    "EXPO_PUBLIC_WEB_APP_URL": "http://127.0.0.1:8081",
    "EXPO_PUBLIC_SUPABASE_ENV": "test",
    "EXPO_PUBLIC_GSH_PAYMENT_STAGING": "1",
    "GSH_PAYMENT_STAGING": "1",
}
for key, value in defaults.items():
    vals.setdefault(key, value)
secret = vals.get("STRIPE_SECRET_KEY", "")
if secret and not secret.startswith("sk_test_"):
    sys.exit("Refusing to write STRIPE_SECRET_KEY: staging accepts sk_test_ only")
if "eaenzjwecrrbhibrvgsb" in "\n".join(vals.values()).lower():
    sys.exit("Refusing to write staging env: production project ref is present")
order = [
    "STAGING_ACCOUNT_PASSWORD",
    "STAGING_DATABASE_URL",
    "EXPO_PUBLIC_SUPABASE_URL",
    "SUPABASE_URL",
    "EXPO_PUBLIC_SUPABASE_ANON_KEY",
    "SUPABASE_SERVICE_ROLE_KEY",
    "EXPO_PUBLIC_WEB_APP_URL",
    "EXPO_PUBLIC_SUPABASE_ENV",
    "EXPO_PUBLIC_GSH_PAYMENT_STAGING",
    "GSH_PAYMENT_STAGING",
    "STRIPE_SECRET_KEY",
    "STRIPE_WEBHOOK_SECRET",
]
lines = [
    "# Generated by scripts/payments/local-staging.sh.",
    "# Gitignored. Do not commit. Do not paste the password into a pull request.",
]
for key in order:
    if key in vals and vals[key] != "":
        lines.append(f"{key}={vals[key]}")
if "STRIPE_SECRET_KEY" not in vals:
    lines.append("# STRIPE_SECRET_KEY=sk_test_...")
if "STRIPE_WEBHOOK_SECRET" not in vals:
    lines.append("# STRIPE_WEBHOOK_SECRET=  # stripe listen --forward-to http://127.0.0.1:3001/api/stripe/webhook")
path.write_text("\n".join(lines) + "\n")
path.chmod(0o600)
print(f"Wrote {path}. The staging password was not printed.")
PY
}

load_env() {
  local legacy="$ROOT/.env.staging.local"
  if [[ -f "$legacy" && "$ENV_FILE" == "$ROOT/staging.local.env" && ! -f "$ENV_FILE" ]]; then
    mv "$legacy" "$ENV_FILE"
    chmod 600 "$ENV_FILE"
  fi
  if [[ -f "$legacy" ]]; then
    echo "Refusing staging: remove .env.staging.local. Expo bundles every project-root .env* file and cannot parse this one. Use staging.local.env." >&2
    exit 1
  fi
  if [[ ! -f "$ENV_FILE" ]]; then
    ensure_env_file
  fi
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
  refuse_value "SUPABASE_URL" "${SUPABASE_URL:-}"
  refuse_value "EXPO_PUBLIC_SUPABASE_URL" "${EXPO_PUBLIC_SUPABASE_URL:-}"
  refuse_value "STAGING_DATABASE_URL" "${STAGING_DATABASE_URL:-}"
  refuse_value "STRIPE_SECRET_KEY" "${STRIPE_SECRET_KEY:-}"
  refuse_value "EXPO_PUBLIC_SUPABASE_ANON_KEY" "${EXPO_PUBLIC_SUPABASE_ANON_KEY:-}"
  if [[ -n "${STRIPE_SECRET_KEY:-}" && "${STRIPE_SECRET_KEY}" != sk_test_* ]]; then
    echo "Refusing staging: STRIPE_SECRET_KEY must start with sk_test_." >&2
    exit 1
  fi
  export GSH_PAYMENT_STAGING=1
  export EXPO_PUBLIC_GSH_PAYMENT_STAGING=1
}

refuse_committed_env_files() {
  python3 - <<'PY'
from pathlib import Path
root = Path(".")
for name in (".env", ".env.local", ".env.development", ".env.development.local"):
    path = root / name
    if not path.exists():
        continue
    text = path.read_text(errors="replace").lower()
    if "eaenzjwecrrbhibrvgsb" in text or "sk_live_" in text or "pk_live_" in text:
        raise SystemExit(f"Refusing staging start: {name} contains a production Supabase ref or a live Stripe key")
PY
}

cmd_seed() {
  load_env
  local host
  if ! host="$(assert_local_database_url "${STAGING_DATABASE_URL}")"; then
    echo "Refusing staging seed: database host is not local." >&2
    exit 1
  fi
  psql -q -v ON_ERROR_STOP=1 \
    "${STAGING_DATABASE_URL}" \
    -v "staging_password=${STAGING_ACCOUNT_PASSWORD}" \
    -v "staging_db_host=${host}" \
    -v "staging_project_ref=local" \
    -f "$SEED_FILE"
  echo "Seeded Staging M4 and Staging ZGS. online_payments_enabled is false."
  echo "Sign in with the addresses in supabase/seeds/staging_m4_zgs_payments.sql."
  echo "The password is only in ${ENV_FILE}."
}

cmd_repair_local_history() {
  load_env
  if ! assert_local_database_url "${STAGING_DATABASE_URL}" >/dev/null; then
    echo "Refusing migration history repair: database host is not local." >&2
    exit 1
  fi
  psql -q -v ON_ERROR_STOP=1 "${STAGING_DATABASE_URL}" <<'SQL'
DO $repair$
BEGIN
  IF to_regclass('supabase_migrations.schema_migrations') IS NULL THEN
    RAISE NOTICE 'no local supabase_migrations.schema_migrations table';
    RETURN;
  END IF;
  UPDATE supabase_migrations.schema_migrations
     SET version = '20261030190000'
   WHERE version = '20261030240000'
     AND NOT EXISTS (
       SELECT 1 FROM supabase_migrations.schema_migrations WHERE version = '20261030190000'
     );
  DELETE FROM supabase_migrations.schema_migrations
   WHERE version = '20261030240000'
     AND EXISTS (
       SELECT 1 FROM supabase_migrations.schema_migrations WHERE version = '20261030190000'
     );
  UPDATE supabase_migrations.schema_migrations
     SET version = '20261030200000'
   WHERE version = '20261030250000'
     AND NOT EXISTS (
       SELECT 1 FROM supabase_migrations.schema_migrations WHERE version = '20261030200000'
     );
  DELETE FROM supabase_migrations.schema_migrations
   WHERE version = '20261030250000'
     AND EXISTS (
       SELECT 1 FROM supabase_migrations.schema_migrations WHERE version = '20261030200000'
     );
  UPDATE supabase_migrations.schema_migrations
     SET version = '20261030210000'
   WHERE version = '20261030260000'
     AND NOT EXISTS (
       SELECT 1 FROM supabase_migrations.schema_migrations WHERE version = '20261030210000'
     );
  DELETE FROM supabase_migrations.schema_migrations
   WHERE version = '20261030260000'
     AND EXISTS (
       SELECT 1 FROM supabase_migrations.schema_migrations WHERE version = '20261030210000'
     );
END
$repair$;
SQL
  echo "Local migration history repaired where the old versions were present."
}

assert_database_name() {
  python3 - "$1" <<'PY'
import sys
name = sys.argv[1]
if not name.replace("_", "").isalnum() or name in {"postgres", "template0", "template1"}:
    sys.exit("Refusing to reset a database that is not a dedicated local staging name")
PY
}

cmd_validate_migrations() {
  if ! command -v supabase >/dev/null 2>&1; then
    echo "supabase CLI is not installed." >&2
    exit 1
  fi
  assert_database_name "$VALIDATE_DB"
  if [[ ! -f "$ROOT/supabase/config.toml" ]]; then
    supabase init
  fi
  psql -d postgres -v ON_ERROR_STOP=1 -q -c "DROP DATABASE IF EXISTS ${VALIDATE_DB};"
  psql -d postgres -v ON_ERROR_STOP=1 -q -c "CREATE DATABASE ${VALIDATE_DB};"
  local url="postgresql://ubuntu@localhost/${VALIDATE_DB}?host=/var/run/postgresql"
  assert_local_database_url "$url" >/dev/null
  echo "Applying migrations with: supabase db reset --db-url <local ${VALIDATE_DB}> --yes --no-seed"
  echo "The CLI calls every --db-url target remote. This URL is local database ${VALIDATE_DB} only."
  supabase db reset --db-url "$url" --yes --no-seed
}

docker_daemon_running() {
  command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1
}

# --runtime native exists only after the experimental stack is enabled.
# Without SUPABASE_EXPERIMENTAL_STACK=1, `supabase start --help` does not list it.
native_runtime_supported() {
  SUPABASE_EXPERIMENTAL_STACK=1 supabase start --help 2>&1 | grep -q -- '--runtime'
}

merge_supabase_status() {
  local status_file="$1"
  python3 - "$ENV_FILE" "$status_file" <<'PY'
import pathlib, sys
env_path, status_path = map(pathlib.Path, sys.argv[1:3])
status = {}
for line in status_path.read_text().splitlines():
    if not line or line.startswith("#") or "=" not in line:
        continue
    key, value = line.split("=", 1)
    status[key] = value.strip().strip('"')
if "ANON_KEY" not in status and status.get("PUBLISHABLE_KEY"):
    status["ANON_KEY"] = status["PUBLISHABLE_KEY"]
if "SERVICE_ROLE_KEY" not in status and status.get("SECRET_KEY"):
    status["SERVICE_ROLE_KEY"] = status["SECRET_KEY"]
mapping = {
    "API_URL": ("EXPO_PUBLIC_SUPABASE_URL", "SUPABASE_URL"),
    "ANON_KEY": ("EXPO_PUBLIC_SUPABASE_ANON_KEY",),
    "SERVICE_ROLE_KEY": ("SUPABASE_SERVICE_ROLE_KEY",),
    "DB_URL": ("STAGING_DATABASE_URL",),
}
text = env_path.read_text().splitlines()
vals = {}
order = []
for line in text:
    if not line or line.startswith("#") or "=" not in line:
        continue
    key, value = line.split("=", 1)
    if key not in vals:
        order.append(key)
    vals[key] = value
for source, targets in mapping.items():
    if source not in status or status[source] == "":
        continue
    if "eaenzjwecrrbhibrvgsb" in status[source].lower():
        sys.exit("Refusing staging: supabase status returned the production project")
    for target in targets:
        vals[target] = status[source]
        if target not in order:
            order.append(target)
lines = [line for line in text if line.startswith("#")]
for key in order:
    lines.append(f"{key}={vals[key]}")
env_path.write_text("\n".join(lines) + "\n")
env_path.chmod(0o600)
PY
}

start_supabase_and_reset() {
  local status_file
  status_file="$(mktemp)"
  chmod 600 "$status_file"
  if [[ "${SUPABASE_EXPERIMENTAL_STACK:-}" == "1" ]]; then
    supabase status --env --output-format text >"$status_file"
  else
    supabase status -o env >"$status_file"
  fi
  merge_supabase_status "$status_file"
  rm -f "$status_file"
  supabase db reset --local --yes --no-seed
}

cmd_setup() {
  ensure_env_file
  load_env
  refuse_committed_env_files
  if [[ ! -f "$ROOT/supabase/config.toml" ]]; then
    supabase init
  fi
  if docker_daemon_running && command -v supabase >/dev/null 2>&1; then
    echo "Starting Supabase with Docker."
    supabase start
    start_supabase_and_reset
  elif command -v supabase >/dev/null 2>&1 && native_runtime_supported; then
    # Do not set [experimental] stack = true in config.toml. That would switch
    # every supabase start in this repo onto the experimental engine.
    export SUPABASE_EXPERIMENTAL_STACK=1
    echo "Docker is not running. Starting the Supabase native runtime."
    echo "CLI $(supabase --version). Migrations stay enabled. Online payments stay off."
    if ! supabase start --runtime native --eager --exclude studio,mail,analytics,realtime,storage,functions,pooler --yes; then
      echo "Native Supabase did not become ready." >&2
      echo "supabase start --help lists --runtime native only when SUPABASE_EXPERIMENTAL_STACK=1." >&2
      echo "A start on this tree stops in supabase/migrations/002_rls_policies.sql because public.societies was never created by a committed migration." >&2
      echo "A Unix-socket Postgres database is not a substitute for Auth and PostgREST." >&2
      exit 1
    fi
    start_supabase_and_reset
  else
    echo "Docker is not running and this Supabase CLI does not offer --runtime native."
    echo "Applying migrations to local database gsh_payment_staging only. Not production."
    echo "This path has no Supabase Auth and no REST API."
    assert_database_name "gsh_payment_staging"
    psql -d postgres -v ON_ERROR_STOP=1 -q -c "DROP DATABASE IF EXISTS gsh_payment_staging;"
    psql -d postgres -v ON_ERROR_STOP=1 -q -c "CREATE DATABASE gsh_payment_staging;"
    supabase db reset --db-url "postgresql://ubuntu@localhost/gsh_payment_staging?host=/var/run/postgresql" --yes --no-seed
  fi
  cmd_repair_local_history || true
  cmd_seed
}

cmd_start() {
  load_env
  refuse_committed_env_files
  if ! assert_local_database_url "${STAGING_DATABASE_URL}" >/dev/null; then
    echo "Refusing staging start: STAGING_DATABASE_URL is not local." >&2
    exit 1
  fi
  export CI="${CI:-1}"
  export EXPO_NO_TELEMETRY=1
  echo "Starting web and payment API against ${EXPO_PUBLIC_SUPABASE_URL}."
  echo "Payment API health: http://127.0.0.1:3001/api/health/db"
  exec npm run dev:web
}

cmd_check() {
  load_env
  curl -fsS "http://127.0.0.1:3001/api/health/db"
  echo
}

command="${1:-}"
case "$command" in
  setup) cmd_setup ;;
  seed) cmd_seed ;;
  start) cmd_start ;;
  check) cmd_check ;;
  repair-local-history) cmd_repair_local_history ;;
  validate-migrations) cmd_validate_migrations ;;
  *) usage; exit 1 ;;
esac
